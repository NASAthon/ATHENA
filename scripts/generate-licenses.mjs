// Writes THIRD_PARTY_LICENSES.md with the full licence text of every direct dependency
// (and the licence summary of all installed packages). Run: npm run licenses
import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const direct = [...Object.keys(pkg.dependencies || {}), ...Object.keys(pkg.devDependencies || {})].sort();

const findLicenseFile = (dir) =>
  readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));

let out = `# Third-Party Licences

ATHENA uses the open-source packages below. Each one's licence text is reproduced
here, as their licences require. Generated by \`npm run licenses\`; don't edit by hand.
Data and content sources (NASA, CDC, ADA and so on) and their terms are listed in \`docs/SOURCES.md\`.

| Package | Version | Licence |
|---|---|---|
`;
const sections = [];
for (const name of direct) {
  const dir = join("node_modules", name);
  if (!existsSync(dir)) continue;
  const p = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const lic = typeof p.license === "string" ? p.license : p.license?.type || "UNKNOWN";
  out += `| ${name} | ${p.version} | ${lic} |\n`;
  const file = findLicenseFile(dir);
  const text = file ? readFileSync(join(dir, file), "utf8").trim() : "(No licence file shipped in the package; licence declared in package.json: " + lic + ")";
  sections.push(`## ${name} (${lic})\n\n\`\`\`\n${text}\n\`\`\`\n`);
}
out += "\n" + sections.join("\n");
writeFileSync("THIRD_PARTY_LICENSES.md", out);
console.log(`Wrote THIRD_PARTY_LICENSES.md for ${sections.length} direct dependencies.`);
